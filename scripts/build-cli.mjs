/**
 * 方案B CLI 构建脚本（esbuild）
 *
 * 两个产物：
 * - out/cli/cli.mjs    方案B 无头单次问答入口（electron/main/cli.ts）
 * - out/cli/cli-ui.mjs 常驻终端界面（TUI）入口（electron/main/cli-ui.tsx 链：
 *   Ink/React 渲染 + WS 流式对话；jsx: automatic 注入 react/jsx-runtime）
 *
 * 共同处理：
 * - electron 模块 → 本地 mock（cli-electron-mock.ts），纯 Node 可加载
 * - @shared 别名 → app/shared（与 electron.vite.config.ts 同款）
 * - node_modules 依赖（express/ws/openai/playwright/ink/react 等）external，
 *   运行时从 app/node_modules 解析
 * - platform=node + format=esm；__dirname/require 由 esbuild 注入 shim
 */

import { build, context } from 'esbuild'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const appRoot = resolve(__dirname, '..')

/** 监听模式：npm run build:cli -- --watch */
const watch = process.argv.includes('--watch')

/** 共享 esbuild 选项：只有 entry/outfile/jsx 不同 */
function makeOptions(entry, outfile, extra = {}) {
  return {
    entryPoints: [resolve(appRoot, entry)],
    outfile: resolve(appRoot, outfile),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    sourcemap: false,
    packages: 'external',
    jsx: 'automatic',
    alias: {
      electron: resolve(appRoot, 'electron/main/cli-electron-mock.ts'),
      '@shared': resolve(appRoot, 'shared')
    },
    logLevel: 'info',
    banner: {
      js: `/* lunar-eclipse CLI - generated by scripts/build-cli.mjs */
import { createRequire as __cliCreateRequire } from 'module';
import { fileURLToPath as __cliFileURLToPath } from 'url';
import { dirname as __cliDirname } from 'path';
const require = __cliCreateRequire(import.meta.url);
const __filename = __cliFileURLToPath(import.meta.url);
const __dirname = __cliDirname(__filename);`
    },
    define: {
      // 纯 Node 下无 electron app.isPackaged；CLI mock 的 app.isPackaged 恒为 false，
      // startup-helpers.getAppAnchor 走 dev 分支（__dirname 上溯两级 = app 目录），与 electron-vite dev 一致
    },
    ...extra
  }
}

const targets = [
  {
    name: 'cli',
    entry: 'electron/main/cli.ts',
    outfile: 'out/cli/cli.mjs'
  },
  {
    name: 'cli-ui',
    entry: 'electron/main/cli-ui.ts',
    outfile: 'out/cli/cli-ui.mjs'
  }
]

if (watch) {
  for (const t of targets) {
    const ctx = await context(makeOptions(t.entry, t.outfile))
    await ctx.watch()
  }
  console.log('[build-cli] watching cli.mjs / cli-ui.mjs ...')
} else {
  await Promise.all(
    targets.map(async (t) => {
      const result = await build(makeOptions(t.entry, t.outfile))
      console.log(`[build-cli] done: ${resolve(appRoot, t.outfile)}`)
      if (result.warnings.length > 0) {
        for (const w of result.warnings) console.warn('[build-cli] warning:', w.text)
      }
      return result
    })
  )
}
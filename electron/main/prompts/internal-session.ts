/** 会话路由：给每条用户消息选「承接哪个内部会话」或「新建一个内部会话」。
 * 定稿语义（逆生树线型）：新会话 = AI 判定话题需要新开（虚线）；继承/时间分支 = 话题延续（实线）。
 * 全量留存：寒暄等一切输入都进入内部会话（无候选时建档兜底），不存在「不值得记录」的输入。 */
export const ROUTER_SYSTEM_PROMPT = `你是会话路由器。每次收到一条用户消息，先判断它该放进哪个内部会话：继续某个已有会话，还是新建一个会话。
内部会话 = AI 后台自维护的上下文池，每个覆盖一段主题/任务。这个用户会话内的全部对话都会被记入内部会话——包括问候、闲聊、简短指令，区别只在放进哪个会话。

摘要 = 会话的「自述」（主题/进展/结论），由 AI 自己写、自己维护：选会话时以摘要为主依据（比标题可靠，标题可能过时）。

逆生树摆放（清单每条带「代际/时间线」标注，按此解读候选）：
- 延续（实线向下）：继承（「第 N 代 / 继承自 <id>」）与时间延续（「时间分叉副本（复制自 <id>）」「已向时间下级 <id> 延续并被锁定」）都是同一话题的延续；只有标注为可继续写入的会话才能承接，锁定/被压缩的会话只能回看
- 新开（虚线向下）：AI 判定当前输入开启了一个需要独立语境的新话题时，新建一条话题线（newTopic=true）

判定（自上而下，命中即止）：
1. 输入延续某候选的主题/任务/语境（追问、继续执行、补充修改、引用该线讨论过的名词/结论/路径；含时间辅助：引用过去时段或"最初怎么聊的"）→ continue 该候选（严格参考其摘要判断，而非只看到标题；摘要为空时再看标题与时间）
2. 输入开启了与全部候选都不重叠的新话题（用户明确开始新工作、或话题 A 切到 B 且 B 不是 A 的延续）→ create 且 newTopic=true（新话题线）
3. 输入没有独立主题（寒暄、问候、单一指令）→ 放进最近更新的会话（continue）；没有任何候选可放时 → create 一个会话容纳它（标题取输入的主题；纯寒暄可用「问候」「闲聊」等概括）
4. create 时新话题与某条候选线相关（同一项目的另一阶段、从该线切换后仍需其背景）→ parentId 取该候选；与所有候选都无关 → 不带 parentId（新树根）

create 行为：
- newTopic=true：新话题线【空白承接】当前输入（不复制任何既有会话内容）；可带 parentId 挂到相关线，也可不带成为新根
- newTopic=false 或缺省：从所选会话【原样继承全部内容】向下延续（消息/摘要/缓存逐字复制），后续对话写进新会话；原会话保持原样作为分叉基点
- 只输出 JSON：{"action": "continue"|"create", "internalId": "<continue 时必填，必须取自清单>", "title": "<create 时的标题>", "summary": "<create 时可选：新会话初始摘要，一句话写清新线干什么>", "parentId": "<create 时可选：挂接的候选 id，必须取自清单>", "newTopic": <create 时：true=新话题线（虚线），false 或缺省=延续复制（实线）>, "reason": "<一句话>"}
- 纯 JSON 输出，不要 markdown 围栏，不要解释`

/**
 * 二次确认：路由选中候选后，确认该候选是否确实承接当前输入。
 * 为什么存在：单次路由二分类容易把主题相近但实际无关的会话误判为 continue（用户指出
 * 「哪怕选择了哪个会话，如果是无关的，AI 也会去新建一个会话，再走下面的流程，之前的
 * 会话不会进入上下文」）。确认环节把「选择」与「注入」解耦：路由选候选 → 确认相关性 →
 * 匹配才注入，不匹配则新建，确保无关会话永不进入上下文。
 * 不删理由：确认是用户明确要求的两步语义（选择→确认→注入）；拒绝模棱两可，
 * 弱匹配宁可新建，避免把错误主题的历史注入当前轮。
 */
export const CONFIRM_SYSTEM_PROMPT = `你是会话相关性确认器。给定用户输入与一个被选中的内部会话（AI 后台上下文池中的一段主题/任务），
判断这个会话是否确实是当前输入需要承接的（即是否把该会话历史注入本轮上下文）。

规则：
- 判断依据主要是该会话的摘要（AI 自己维护的主题/进展/结论自述）：输入明显延续摘要所述的主题、语境或任务（含引用该会话讨论过的具体内容）→ matched: true
- 输入与本会话主题无关、或只是宽泛的相关话题但缺少实质承接关系 → matched: false
- 没有把握时不猜：宁可 false（调用方会新建独立会话）也不要误注入无关历史
- 判断为 false 时：调用方会新建一个【新话题】空白承接当前输入（不复制你这次否定的会话的任何内容），你只需判断相关性，不用考虑新建细节
- 只输出 JSON：{"matched": true|false, "reason": "<一句话理由>"}
- 纯 JSON 输出，不要 markdown 围栏，不要解释`


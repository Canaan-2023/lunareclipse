/**
 * ROOM 自主规划轮的提示词纪律（0.53.10）。
 *
 * 为什么需要独立一份：ROOM 规划轮此前复用通用对话提示词，而通用提示词里有几条
 * **与自主规划直接冲突**的规则：
 * - 「工具调用之外输出的所有文本展示给用户」→ 规划轮的正文是 JSON 计划，不是给用户的话；
 * - 「每轮要有实际工具调用，不空转」→ 自主轮允许「没有任务，decisions 为空」；
 * - 「任务完成输出 [TASK_COMPLETE]」→ 这是对话/编码链路的收尾标记，规划轮不用；
 * - output_discipline 的「正文是对用户输入的回复」→ 规划轮的正文是计划契约。
 *
 * 处理方式：不删除通用提示词（它同时承担身份、记忆检索、工具用法），而是在
 * `purpose==='room'` 时用本文件的 ROOM 版输出纪律替换 output_discipline，并在
 * 注入链末尾追加 ROOM_CONTRACT_PROMPT（离用户消息最近，优先级最高）。
 */
export const ROOM_OUTPUT_DISCIPLINE_PROMPT = `## 输出纪律（ROOM 自主规划轮）

你的输出分思考（reasoning）与正文（content）两部分。思考只出现在思考流，不写进正文、不进入会话上下文。

正文必须是**且只是**一个 JSON 对象（契约见本轮规划消息的【输出契约】）：
- 不要 markdown 代码块包裹，不要前后解释，不要在 JSON 之外写任何文字；
- 不要输出 [TASK_COMPLETE]、[TIMER:...]、[TIMER_CANCEL:...] 等对话/编码链路的标记；
- 本轮自主节奏用 JSON 的 standbyMs 表达，不用定时器标记；
- 没有可做的事就输出 {"note":"无需动作","decisions":[]}——空计划是合法结果，不要为了「显得在干活」而编造动作。

你的正文不是给用户的聊天回复：只有 JSON 里的 reply / scene.say 会被当作给用户看的话。`

export const ROOM_CONTRACT_PROMPT = `## ROOM 自主规划轮（当前生效，覆盖通用对话规则）

本轮不是与用户对话，而是你在自己的房间（ROOM）里的自主规划轮。以下规则优先于通用提示词里与之冲突的部分：

1. **输出**：只输出一个 JSON 对象，字段与取值以本轮规划消息的【输出契约】为准。JSON 之外的内容会被丢弃；无法解析为本合约时，本轮不会执行任何动作。
2. **覆盖**：通用提示词中的「所有文本展示给用户」「每轮必须有工具调用」「任务完成输出 [TASK_COMPLETE]」等对话规则不适用于本轮；以本段与【输出契约】为准。
3. **工具**：只能从本轮规划消息的【可调用工具】里选择。系统工具清单里的其它工具本轮不可用，写进 decisions 会被丢弃。
4. **任务**：有没有任务、做什么、做多少，都由你判断。采集输入里没有任务时，不要编造任务；不需要动作就让 decisions 为空。
5. **用户**：只有采集输入里出现【用户刚说的话】时，才用 reply 回应；reply 会作为直播字幕显示并落回会话历史。
6. **记忆**：需要历史事实时用你自己的记忆/会话工具查；不要凭印象编造记忆内容。
7. **等待**：暂时不需要主动做事时，用 standbyMs 声明等待时长；感知器仍会在环境真的变化时提前叫醒你。
8. **失败**：工具或规划调用失败时如实说明（note / reply），不要假装成功；不要用重复动作掩盖失败。`

/**
 * 采集器配置（ROOM 记忆区的输入源）。
 * 为什么存在：交接单 §7 要求采集器「默认关、范围可配、用户可见」——采集范围与开关必须可配置，
 * 且与主进程采集实现共享同一契约。
 * 作用：定义采集开关与采集源（环境状态 / 桌面）。
 */

/** 采集源：环境状态（CPU/内存/负载/平台）、桌面（整屏截图）、系统（后台进程 + 上传下载）。 */
export interface CollectorConfig {
  /** 总开关；false/undefined = 不采集（安全默认：默认关） */
  enabled: boolean
  /** 是否允许采集桌面（整屏截图）——比环境状态更敏感，单独开关 */
  desktop: boolean
  /** 是否允许采集后台进程列表（名称/PID/内存） */
  processes?: boolean
  /** 是否允许监控上传/下载（系统网卡速率 + 本应用传输） */
  network?: boolean
}
